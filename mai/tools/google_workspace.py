"""Owner-only Google Drive and Sheets native tools.

Credentials are generated by scripts/google_oauth_login.py. OAuth tokens never
enter the repository and are not exposed as tool results.
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import Any

from google.auth.transport.requests import Request
from google.oauth2.credentials import Credentials
from googleapiclient.discovery import build
from pydantic import BaseModel, ConfigDict, Field

from .registry import ToolRegistry


SCOPES = (
    "https://www.googleapis.com/auth/drive.metadata.readonly",
    "https://www.googleapis.com/auth/spreadsheets",
)


class GoogleNotConfiguredError(RuntimeError):
    """Google OAuth has not been configured for this MAI instance."""


def _credentials() -> Credentials:
    path_string = os.environ.get("GOOGLE_OAUTH_TOKEN_PATH")
    if not path_string:
        raise GoogleNotConfiguredError("GOOGLE_OAUTH_TOKEN_PATH is not configured")
    path = Path(path_string).expanduser().resolve()
    if not path.is_file():
        raise GoogleNotConfiguredError(
            "Google OAuth token file does not exist; run scripts/google_oauth_login.py"
        )
    credentials = Credentials.from_authorized_user_file(str(path), scopes=list(SCOPES))
    if credentials.expired and credentials.refresh_token:
        credentials.refresh(Request())
        path.write_text(credentials.to_json(), encoding="utf-8")
    if not credentials.valid:
        raise GoogleNotConfiguredError("Google OAuth credentials are not valid")
    return credentials


def _service(api: str, version: str) -> Any:
    return build(api, version, credentials=_credentials(), cache_discovery=False)


class _StrictInput(BaseModel):
    model_config = ConfigDict(extra="forbid")


class DriveSearchInput(_StrictInput):
    query: str = Field(description="Google Drive API files.list q expression, e.g. name contains 'budget'")
    page_size: int = Field(default=30, ge=1, le=100)
    page_token: str | None = None


class DriveFileInput(_StrictInput):
    file_id: str = Field(min_length=1)


class SheetMetadataInput(_StrictInput):
    spreadsheet_id: str = Field(min_length=1)


class SheetReadInput(SheetMetadataInput):
    range: str = Field(min_length=1, description="A1 notation, including quoted tab name where needed")


class SheetWriteInput(SheetReadInput):
    values: list[list[str | int | float | bool | None]]
    value_input_option: str = Field(default="USER_ENTERED", pattern="^(RAW|USER_ENTERED)$")


class SheetAppendInput(SheetWriteInput):
    insert_data_option: str = Field(default="INSERT_ROWS", pattern="^(INSERT_ROWS|OVERWRITE)$")


class SheetClearInput(SheetReadInput):
    pass


def google_drive_search(query: str, page_size: int = 30, page_token: str | None = None) -> dict:
    args: dict[str, Any] = {
        "q": query,
        "pageSize": page_size,
        "fields": "nextPageToken,files(id,name,mimeType,parents,webViewLink,modifiedTime,description)",
    }
    if page_token is not None:
        args["pageToken"] = page_token
    return _service("drive", "v3").files().list(**args).execute()


def google_drive_get_file(file_id: str) -> dict:
    return _service("drive", "v3").files().get(
        fileId=file_id, fields="id,name,mimeType,parents,webViewLink,modifiedTime,description"
    ).execute()


def google_sheets_metadata(spreadsheet_id: str) -> dict:
    return _service("sheets", "v4").spreadsheets().get(
        spreadsheetId=spreadsheet_id,
        fields="spreadsheetId,spreadsheetUrl,properties(title),sheets(properties(sheetId,title,index,gridProperties))",
    ).execute()


def google_sheets_read(spreadsheet_id: str, range: str) -> dict:
    return _service("sheets", "v4").spreadsheets().values().get(
        spreadsheetId=spreadsheet_id, range=range
    ).execute()


def google_sheets_write(
    spreadsheet_id: str, range: str, values: list[list[str | int | float | bool | None]],
    value_input_option: str = "USER_ENTERED",
) -> dict:
    return _service("sheets", "v4").spreadsheets().values().update(
        spreadsheetId=spreadsheet_id, range=range,
        valueInputOption=value_input_option, body={"values": values},
    ).execute()


def google_sheets_append(
    spreadsheet_id: str, range: str, values: list[list[str | int | float | bool | None]],
    value_input_option: str = "USER_ENTERED", insert_data_option: str = "INSERT_ROWS",
) -> dict:
    return _service("sheets", "v4").spreadsheets().values().append(
        spreadsheetId=spreadsheet_id, range=range, valueInputOption=value_input_option,
        insertDataOption=insert_data_option, body={"values": values},
    ).execute()


def google_sheets_clear(spreadsheet_id: str, range: str) -> dict:
    return _service("sheets", "v4").spreadsheets().values().clear(
        spreadsheetId=spreadsheet_id, range=range, body={},
    ).execute()


def register_google_tools(registry: ToolRegistry) -> None:
    """Register Google API tools for an authorized owner only.

    Caller MUST enforce the owner role before invoking this function.
    Google tools are not offered when OAuth is not configured.
    """
    if not os.environ.get("GOOGLE_OAUTH_TOKEN_PATH"):
        return
    specifications = (
        ("google_drive_search", "Search Drive files with Google Drive q syntax; returns IDs and pagination token.", DriveSearchInput, google_drive_search),
        ("google_drive_get_file", "Read Drive file metadata using its exact file ID.", DriveFileInput, google_drive_get_file),
        ("google_sheets_metadata", "Inspect spreadsheet tabs and dimensions from its ID.", SheetMetadataInput, google_sheets_metadata),
        ("google_sheets_read", "Read live cell values from an A1 range of a Google spreadsheet.", SheetReadInput, google_sheets_read),
        ("google_sheets_write", "Update an existing A1 cell range in Google Sheets; changes are permanent.", SheetWriteInput, google_sheets_write),
        ("google_sheets_append", "Append rows to a Google Sheet table; changes are permanent.", SheetAppendInput, google_sheets_append),
        ("google_sheets_clear", "Clear values in an A1 range; destructive and permanent.", SheetClearInput, google_sheets_clear),
    )
    for name, description, input_model, handler in specifications:
        registry.add(
            name=name, description=description, input_model=input_model,
            handler=handler, timeout_seconds=40, category="google",
        )
